function tri(en, ru, uk) {
    return { en, ru, uk };
}

function isLeaf(value) {
    return Boolean(
        value
        && typeof value === 'object'
        && typeof value.en === 'string'
        && typeof value.ru === 'string'
        && typeof value.uk === 'string'
        && Object.keys(value).every((key) => key === 'en' || key === 'ru' || key === 'uk'),
    );
}

function buildMessages(tree) {
    const locales = { en: {}, ru: {}, uk: {} };

    const walk = (node, parents) => {
        Object.entries(node).forEach(([key, value]) => {
            if (isLeaf(value)) {
                let enRef = locales.en;
                let ruRef = locales.ru;
                let ukRef = locales.uk;
                parents.forEach((part) => {
                    enRef[part] ??= {};
                    ruRef[part] ??= {};
                    ukRef[part] ??= {};
                    enRef = enRef[part];
                    ruRef = ruRef[part];
                    ukRef = ukRef[part];
                });
                enRef[key] = value.en;
                ruRef[key] = value.ru;
                ukRef[key] = value.uk;
                return;
            }

            walk(value, [...parents, key]);
        });
    };

    walk(tree, []);

    return locales;
}

